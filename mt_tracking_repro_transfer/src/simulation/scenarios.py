"""Phase 2 deterministic scenario construction.

Phase 1 / Phase 1.5 store datasets that are generated by
``src.simulation.dataset.simulate_scenario``. That generator intentionally
hard-codes a crossing scene for its first four targets and deterministic
lifetimes. Phase 2 needs *controlled* scenarios (non-crossing lanes, requested
lifetimes, a temporary detection gap) without touching the tracker or the
existing dataset code.

This module builds the same ``SimulationData`` structure that the tracker and
evaluator already consume, but derives initial motion, lifetimes and detection
gaps from an explicit :class:`ScenarioSpec`. It does not modify
``dataset.py`` and does not change any Phase 1 artifact.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

import numpy as np
import yaml

from .dataset import Detection, ScenarioConfig, SimulationData


Array = np.ndarray


# Motion layouts supported by the scenario builder. ``solo`` is a single
# straight-line target; ``parallel`` places targets on non-crossing lanes that
# all translate with the same heading; ``crossing`` sends two groups toward each
# other so their straight-line paths intersect.
MOTION_MODES = ("solo", "parallel", "crossing")


@dataclass
class ScenarioSpec:
    """Fully resolved, deterministic description of a Phase 2 scenario."""

    name: str
    distribution: str
    steps: int
    num_targets: int
    area_size: float
    detection_probability: float
    measurement_std: float
    clutter_rate: float
    process_accel_std: float
    seed: int
    motion: str = "parallel"
    lifetimes: Optional[List[Tuple[int, int]]] = None
    # (target_index, start_frame, end_frame) windows with the target present in
    # truth but forced to produce no detection.
    disappearance: List[Tuple[int, int, int]] = field(default_factory=list)
    description: str = ""

    def to_config(self) -> ScenarioConfig:
        return ScenarioConfig(
            steps=self.steps,
            num_targets=self.num_targets,
            area_size=self.area_size,
            detection_probability=self.detection_probability,
            measurement_std=self.measurement_std,
            clutter_rate=self.clutter_rate,
            process_accel_std=self.process_accel_std,
            seed=self.seed,
        )

    def resolved(self) -> dict:
        payload = asdict(self)
        payload["lifetimes"] = [list(pair) for pair in self.lifetimes] if self.lifetimes else None
        payload["disappearance"] = [list(window) for window in self.disappearance]
        return payload


def _validate_spec(spec: ScenarioSpec) -> None:
    if spec.motion not in MOTION_MODES:
        raise ValueError(f"unknown motion mode {spec.motion!r}; expected one of {MOTION_MODES}")
    if spec.num_targets < 1 or spec.steps < 2:
        raise ValueError("num_targets must be >= 1 and steps must be >= 2")
    if not 0.0 <= spec.detection_probability <= 1.0:
        raise ValueError("detection_probability must be between 0 and 1")
    if spec.measurement_std < 0 or spec.process_accel_std < 0 or spec.clutter_rate < 0:
        raise ValueError("noise and clutter parameters must be >= 0")
    if spec.lifetimes is not None:
        if len(spec.lifetimes) != spec.num_targets:
            raise ValueError("lifetimes must contain one [birth, death] pair per target")
        for birth, death in spec.lifetimes:
            if not 0 <= birth < death <= spec.steps:
                raise ValueError(
                    f"invalid lifetime ({birth}, {death}) for horizon {spec.steps}"
                )
    for target, start, end in spec.disappearance:
        if not 0 <= target < spec.num_targets:
            raise ValueError("disappearance target index out of range")
        if not 0 <= start < end <= spec.steps:
            raise ValueError("invalid disappearance window")


def _lifetimes(spec: ScenarioSpec) -> Tuple[Array, Array]:
    if spec.lifetimes is not None:
        births = np.array([birth for birth, _ in spec.lifetimes], dtype=int)
        deaths = np.array([death for _, death in spec.lifetimes], dtype=int)
        return births, deaths
    return np.zeros(spec.num_targets, dtype=int), np.full(spec.num_targets, spec.steps, dtype=int)


def _initial_conditions(spec: ScenarioSpec) -> Tuple[Array, Array]:
    """Deterministic initial positions/velocities for the requested motion.

    Motion is not sampled (it must be intentional), so no RNG is consumed here.
    This keeps the target layout independent of the noise stream, which makes
    the scenarios easier to reason about and reproduce.
    """

    n = spec.num_targets
    area = spec.area_size
    positions = np.zeros((n, 2), dtype=float)
    velocities = np.zeros((n, 2), dtype=float)

    if spec.motion == "solo":
        for index in range(n):
            offset = 6.0 * (index - (n - 1) / 2.0)
            positions[index] = [0.15 * area, 0.5 * area + offset]
            velocities[index] = [0.9, 0.0]
    elif spec.motion == "parallel":
        lanes = np.linspace(0.12 * area, 0.88 * area, n) if n > 1 else np.array([0.5 * area])
        for index in range(n):
            positions[index] = [0.15 * area, lanes[index]]
            velocities[index] = [0.8, 0.0]
    elif spec.motion == "crossing":
        # Two groups converge toward the middle, guaranteeing path crossings.
        for index in range(n):
            group_index = index // 2
            start_x = 0.12 * area + 8.0 * group_index
            if index % 2 == 0:
                positions[index] = [start_x, 0.30 * area]
                velocities[index] = [1.2, 0.35]
            else:
                positions[index] = [start_x, 0.70 * area]
                velocities[index] = [1.2, -0.35]
    else:  # pragma: no cover - guarded by _validate_spec
        raise ValueError(f"unknown motion mode {spec.motion!r}")

    return positions, velocities


def _detection_gap(spec: ScenarioSpec, target: int, time: int) -> bool:
    return any(
        window_target == target and start <= time < end
        for window_target, start, end in spec.disappearance
    )


def generate_scenario(spec: ScenarioSpec) -> SimulationData:
    """Generate truth and detections for one Phase 2 scenario.

    Semantics mirror ``dataset.simulate_scenario`` (reflect at the surveillance
    boundary, per-frame process acceleration after birth, per-detection Gaussian
    measurement noise, Poisson clutter uniform over the area) so that metrics are
    comparable across phases.
    """

    _validate_spec(spec)
    config = spec.to_config()
    rng = np.random.default_rng(spec.seed)
    births, deaths = _lifetimes(spec)
    positions, velocities = _initial_conditions(spec)
    truth = np.full((spec.steps, spec.num_targets, 4), np.nan, dtype=float)
    detections: List[List[Detection]] = []

    for time in range(spec.steps):
        frame_detections: List[Detection] = []
        for target in range(spec.num_targets):
            active = births[target] <= time < deaths[target]
            if not active:
                continue
            if time > births[target]:
                velocities[target] += rng.normal(0.0, spec.process_accel_std, 2)
                positions[target] += velocities[target]
                for axis in (0, 1):
                    low, high = 5.0, spec.area_size - 5.0
                    if positions[target, axis] < low or positions[target, axis] > high:
                        velocities[target, axis] *= -1.0
                        positions[target, axis] = float(np.clip(positions[target, axis], low, high))
            truth[time, target, :2] = positions[target]
            truth[time, target, 2:] = velocities[target]
            if _detection_gap(spec, target, time):
                continue
            if rng.random() < spec.detection_probability:
                measured = positions[target] + rng.normal(0.0, spec.measurement_std, 2)
                frame_detections.append(Detection(measured, target))

        clutter_count = int(rng.poisson(spec.clutter_rate))
        for _ in range(clutter_count):
            frame_detections.append(Detection(rng.uniform(0.0, spec.area_size, 2), None))
        rng.shuffle(frame_detections)
        detections.append(frame_detections)

    return SimulationData(truth, detections, births, deaths, config)


def _build_spec(
    name: str,
    distribution: str,
    scenario_config: dict,
    distribution_config: dict,
) -> ScenarioSpec:
    default_keys = (
        "steps",
        "area_size",
        "detection_probability",
        "measurement_std",
        "clutter_rate",
        "process_accel_std",
    )
    resolved = {key: distribution_config["defaults"][key] for key in default_keys}
    for key in default_keys:
        if key in scenario_config:
            resolved[key] = scenario_config[key]
    clutter_by_distribution = scenario_config.get("clutter_rate_by_distribution", {})
    if distribution in clutter_by_distribution:
        resolved["clutter_rate"] = clutter_by_distribution[distribution]

    seed = int(scenario_config["seed"]) + int(distribution_config.get("seed_offset", 0))
    lifetimes = scenario_config.get("lifetimes")
    disappearance = [
        (int(window["target"]), int(window["start"]), int(window["end"]))
        for window in scenario_config.get("disappearance", [])
    ]
    return ScenarioSpec(
        name=name,
        distribution=distribution,
        steps=int(resolved["steps"]),
        num_targets=int(scenario_config["num_targets"]),
        area_size=float(resolved["area_size"]),
        detection_probability=float(resolved["detection_probability"]),
        measurement_std=float(resolved["measurement_std"]),
        clutter_rate=float(resolved["clutter_rate"]),
        process_accel_std=float(resolved["process_accel_std"]),
        seed=seed,
        motion=str(scenario_config.get("motion", "parallel")),
        lifetimes=[(int(birth), int(death)) for birth, death in lifetimes] if lifetimes else None,
        disappearance=disappearance,
        description=str(scenario_config.get("description", "")),
    )


def resolve_scenarios(
    config_path: Path,
    scenarios: Optional[Sequence[str]] = None,
    distributions: Optional[Sequence[str]] = None,
) -> Tuple[float, List[ScenarioSpec]]:
    """Resolve the Phase 2 matrix from YAML into concrete :class:`ScenarioSpec`s."""

    with Path(config_path).open(encoding="utf-8") as handle:
        configuration = yaml.safe_load(handle)

    match_gate = float(configuration.get("match_gate", 12.0))
    all_scenarios = configuration["scenarios"]
    all_distributions = configuration["distributions"]

    selected_scenarios = list(scenarios) if scenarios else list(all_scenarios)
    selected_distributions = list(distributions) if distributions else list(all_distributions)

    unknown_scenarios = [name for name in selected_scenarios if name not in all_scenarios]
    if unknown_scenarios:
        raise ValueError(f"unknown scenario(s): {', '.join(unknown_scenarios)}")
    unknown_distributions = [name for name in selected_distributions if name not in all_distributions]
    if unknown_distributions:
        raise ValueError(f"unknown distribution(s): {', '.join(unknown_distributions)}")

    specs: List[ScenarioSpec] = []
    for distribution in selected_distributions:
        for scenario in selected_scenarios:
            specs.append(
                _build_spec(
                    scenario,
                    distribution,
                    all_scenarios[scenario],
                    all_distributions[distribution],
                )
            )
    return match_gate, specs
